export const designToWorld = ([x, y]) => ({
  x: (x - 500) * 4,
  z: (y - 600) * 4,
});
export function inspectionPose(spec, view) {
  const o = designToWorld(spec.target),
    r = spec.radius,
    h = spec.height;
  const offset =
    view === "ground"
      ? [r * 0.1, 3, r * 0.72]
      : view === "river"
        ? [-r, Math.max(16, h * 0.5), -r * 0.25]
        : view === "night"
          ? [r * 0.65, Math.max(10, h * 0.35), r * 0.75]
          : [r * 0.64, Math.max(70, r * 0.72), r * 0.76];
  return {
    position: [o.x + offset[0], offset[1], o.z + offset[2]],
    look: [o.x, view === "ground" ? 3 : Math.min(30, h * 0.35), o.z],
  };
}
